const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function packageFor(input) {
  let directory = path.dirname(path.resolve(root, input));
  while (directory.startsWith(path.join(root, 'node_modules') + path.sep)) {
    const filename = path.join(directory, 'package.json');
    if (fs.existsSync(filename)) {
      const manifest = JSON.parse(fs.readFileSync(filename, 'utf8'));
      if (manifest.name && manifest.version) return { directory, manifest };
    }
    directory = path.dirname(directory);
  }
  throw new Error(`Cannot identify bundled dependency: ${input}`);
}

function writeNotices(metafiles) {
  const packages = new Map();
  for (const metadata of metafiles) {
    for (const output of Object.values(metadata.outputs)) {
      for (const [input, included] of Object.entries(output.inputs)) {
        if (!input.replaceAll('\\', '/').includes('node_modules/') || included.bytesInOutput === 0) continue;
        const item = packageFor(input);
        packages.set(`${item.manifest.name}@${item.manifest.version}`, item);
      }
    }
  }
  const sections = [
    'Third-party notices for Browser MCP Debug',
    'Generated by npm run bundle from packages included in the runtime bundles.\nDevelopment-only dependencies are not distributed. Playwright MCP and Chrome\nDevTools MCP are downloaded and run separately; their own distributions carry\ntheir respective licenses. Chrome and VS Code are not bundled.'
  ];
  for (const [name, { directory, manifest }] of [...packages.entries()].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    const files = fs.readdirSync(directory).filter(file => /^(?:licen[sc]e|notice)(?:[._-].*)?$/i.test(file) && fs.statSync(path.join(directory, file)).isFile()).sort();
    if (!files.some(file => /^licen[sc]e/i.test(file))) throw new Error(`No license text found for bundled dependency ${name}.`);
    sections.push(`===============================================================================\n${name}\nLicense: ${manifest.license || 'See license text below'}\n\n${files.map(file => `${file}\n\n${fs.readFileSync(path.join(directory, file), 'utf8').trim()}`).join('\n\n')}`);
  }
  fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.txt'), sections.join('\n\n') + '\n');
  console.log(`Generated THIRD_PARTY_NOTICES.txt for ${packages.size} bundled dependencies.`);
}
module.exports = { writeNotices };
